import { describe, expect, it } from 'vitest';
import { detectDelimiter, parseCsv } from './csv-parse';

describe('detectDelimiter', () => {
  it.each([
    ['русский Excel: точка с запятой', 'Контрагент;Дата печати;Остаток\n1;2;3', ';'],
    ['английский Excel: запятая', 'Контрагент,Дата печати,Остаток\n1;2;3', ','],
    ['одна колонка без разделителей — `;` по умолчанию', 'Контрагент', ';'],
    ['пустой текст — `;`', '', ';'],
    ['поровну — `;`', 'a;b,c', ';'],
    ['считается только первая строка', 'a;b;c\n1,2,3,4,5,6', ';'],
    ['первая строка с CRLF', 'a,b\r\n;;;;', ','],
  ])('%s', (_name, text, expected) => {
    expect(detectDelimiter(text)).toBe(expected);
  });
});

describe('parseCsv', () => {
  it('простые строки с `;`', () => {
    expect(parseCsv('a;b;c\n1;2;3')).toEqual([
      ['a', 'b', 'c'],
      ['1', '2', '3'],
    ]);
  });

  it('разделитель `,` определяется по заголовку', () => {
    expect(parseCsv('a,b\n1,2')).toEqual([
      ['a', 'b'],
      ['1', '2'],
    ]);
  });

  it('при `;` запятая внутри ячейки — обычный символ', () => {
    expect(parseCsv('a;b\nООО, Ромашка;2')).toEqual([
      ['a', 'b'],
      ['ООО, Ромашка', '2'],
    ]);
  });

  it('BOM в начале отрезается и не попадает в первый заголовок', () => {
    expect(parseCsv('\uFEFFКонтрагент;Остаток\nА;1')[0]).toEqual(['Контрагент', 'Остаток']);
  });

  it('BOM не мешает определить разделитель', () => {
    expect(parseCsv('\uFEFFa,b\n1,2')).toEqual([
      ['a', 'b'],
      ['1', '2'],
    ]);
  });

  it('CRLF и одиночный LF', () => {
    expect(parseCsv('a;b\r\n1;2\n3;4\r\n')).toEqual([
      ['a', 'b'],
      ['1', '2'],
      ['3', '4'],
    ]);
  });

  it('кавычки: разделитель, удвоенные кавычки и переводы строк внутри ячейки', () => {
    expect(parseCsv('a;b\n"x;y";"ООО ""Ромашка"""\n"две\r\nстроки";z')).toEqual([
      ['a', 'b'],
      ['x;y', 'ООО "Ромашка"'],
      ['две\r\nстроки', 'z'],
    ]);
  });

  it('пустая ячейка в кавычках', () => {
    expect(parseCsv('a;b;c\n"";x;""')).toEqual([
      ['a', 'b', 'c'],
      ['', 'x', ''],
    ]);
  });

  it('кавычка в середине ячейки без кавычек — обычный символ', () => {
    expect(parseCsv('a;b\n12"34;x')).toEqual([
      ['a', 'b'],
      ['12"34', 'x'],
    ]);
  });

  it('незакрытая кавычка забирает остаток файла в одну ячейку, без исключения', () => {
    expect(parseCsv('a;b\n"x;y\n1;2')).toEqual([['a', 'b'], ['x;y\n1;2']]);
  });

  it('пустые строки и строки из одних разделителей и пробелов пропускаются', () => {
    expect(parseCsv('a;b\n\n;\n  ; \r\n1;2\n\n')).toEqual([
      ['a', 'b'],
      ['1', '2'],
    ]);
  });

  it('последняя строка без перевода строки', () => {
    expect(parseCsv('a;b\n1;2')).toHaveLength(2);
  });

  it('пустые ячейки в конце строки сохраняются', () => {
    expect(parseCsv('a;b;c\n1;;')).toEqual([
      ['a', 'b', 'c'],
      ['1', '', ''],
    ]);
  });

  it('пустой ввод и только BOM — пустой список', () => {
    expect(parseCsv('')).toEqual([]);
    expect(parseCsv('\uFEFF')).toEqual([]);
    expect(parseCsv('\n\r\n')).toEqual([]);
  });

  it('BOM не в начале не трогается', () => {
    expect(parseCsv('a\n\uFEFFb')).toEqual([['a'], ['\uFEFFb']]);
  });

  it('символ NUL доходит до ячейки как есть — проверка ниже по течению', () => {
    expect(parseCsv('a;b\nx\0y;1')[1]).toEqual(['x\0y', '1']);
  });
});
