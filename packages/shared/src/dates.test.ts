import { describe, expect, it } from 'vitest';
import { formatIsoDateRu, isValidIsoDate, parseRuOrIsoDate, todayIsoDate } from './dates';

describe('isValidIsoDate', () => {
  it.each(['2026-11-01', '2028-02-29', '2000-02-29', '2026-12-31', '1900-01-01', '2026-04-30'])(
    'валидная дата: %s',
    (value) => {
      expect(isValidIsoDate(value)).toBe(true);
    },
  );

  it.each([
    ['29 февраля не високосного года', '2026-02-29'],
    ['1900 — не високосный', '1900-02-29'],
    ['13-й месяц', '2026-13-01'],
    ['нулевой месяц', '2026-00-10'],
    ['31 апреля', '2026-04-31'],
    ['нулевой день', '2026-05-00'],
    ['32-й день', '2026-01-32'],
    ['год до 1900', '1899-12-31'],
    ['русский формат', '01.11.2026'],
    ['без ведущих нулей', '2026-1-1'],
    ['со временем', '2026-11-01T00:00:00Z'],
    ['пробелы по краям', ' 2026-11-01 '],
    ['пустая строка', ''],
    ['мусор', 'вчера'],
  ])('невалидная дата (%s): %s', (_name, value) => {
    expect(isValidIsoDate(value)).toBe(false);
  });
});

describe('todayIsoDate', () => {
  it('берёт локальную дату с ведущими нулями', () => {
    expect(todayIsoDate(new Date(2026, 0, 5, 23, 59))).toBe('2026-01-05');
  });

  it('полночь по местному времени не сдвигает день', () => {
    expect(todayIsoDate(new Date(2026, 10, 9, 0, 0))).toBe('2026-11-09');
  });
});

describe('formatIsoDateRu', () => {
  it('переводит ISO в ДД.ММ.ГГГГ', () => {
    expect(formatIsoDateRu('2026-11-01')).toBe('01.11.2026');
  });

  it('нераспознанное значение возвращает как есть', () => {
    expect(formatIsoDateRu('мусор')).toBe('мусор');
    expect(formatIsoDateRu('')).toBe('');
  });
});

describe('parseRuOrIsoDate', () => {
  it.each([
    ['русский формат', '01.11.2026', '2026-11-01'],
    ['без ведущего нуля в дне', '1.11.2026', '2026-11-01'],
    ['без ведущих нулей', '1.1.2026', '2026-01-01'],
    ['ISO', '2026-11-01', '2026-11-01'],
    ['пробелы по краям', ' 01.11.2026\t', '2026-11-01'],
    ['пробелы вокруг ISO', ' 2026-11-01 ', '2026-11-01'],
    ['29 февраля високосного года', '29.02.2028', '2028-02-29'],
    ['конец года', '31.12.2026', '2026-12-31'],
    ['нижняя граница', '01.01.1900', '1900-01-01'],
  ])('%s: %j → %s', (_name, value, expected) => {
    expect(parseRuOrIsoDate(value)).toBe(expected);
  });

  it.each([
    ['пустая строка', ''],
    ['только пробелы', '   '],
    ['29 февраля невисокосного года', '29.02.2026'],
    ['31 апреля', '31.04.2026'],
    ['13-й месяц', '01.13.2026'],
    ['нулевой день', '00.11.2026'],
    ['нулевой месяц', '01.00.2026'],
    ['год двумя цифрами', '01.11.26'],
    ['трёхзначный день', '001.11.2026'],
    ['год до 1900', '31.12.1899'],
    ['слэши', '01/11/2026'],
    ['дефисы в русском порядке', '01-11-2026'],
    ['ISO без ведущих нулей', '2026-1-1'],
    ['со временем', '01.11.2026 10:00'],
    ['ISO со временем', '2026-11-01T00:00:00Z'],
    ['точка в конце', '01.11.2026.'],
    ['мусор', 'вчера'],
    ['число Excel', '46327'],
  ])('%s: %j → null', (_name, value) => {
    expect(parseRuOrIsoDate(value)).toBeNull();
  });
});
